func writeGoAttributes(buf *bytes.Buffer, attrs []Attribute, depth int) {
	tabs := func(n int) string {
		b := make([]byte, n)
		for i := range b {
			b[i] = '\t'
		}
		return string(b)
	}
	t := tabs(depth)
	buf.WriteString("[]Attribute{\n")
	for _, a := range attrs {
		fmt.Fprintf(buf, "%s\t{\n", t)
		fmt.Fprintf(buf, "%s\t\tKey: %q, LabelDE: %q, ValueType: %q,\n", t, a.Key, a.LabelDE, a.ValueType)
		if a.OptionSetKey != "" {
			fmt.Fprintf(buf, "%s\t\tOptionSetKey: %q,\n", t, a.OptionSetKey)
		}
		if a.UnitGroup != "" {
			fmt.Fprintf(buf, "%s\t\tUnitGroup: %q,\n", t, a.UnitGroup)
		}
		if len(a.AllowedUnits) > 0 {
			fmt.Fprintf(buf, "%s\t\tAllowedUnits: %s,\n", t, goStringSlice(a.AllowedUnits))
		}
		if a.Required {
			fmt.Fprintf(buf, "%s\t\tRequired: true,\n", t)
		}
		if a.ShowWhen != nil {
			fmt.Fprintf(buf, "%s\t\tShowWhen: &ShowWhenSpec{Field: %q, Value: %q},\n",
				t, a.ShowWhen.Field, a.ShowWhen.Value)
		}
		if len(a.VisibleWhen) > 0 {
			fmt.Fprintf(buf, "%s\t\tVisibleWhen: %s,\n", t, goConditionSlice(a.VisibleWhen))
		}
		if len(a.AppliesToGearWhen) > 0 {
			fmt.Fprintf(buf, "%s\t\tAppliesToGearWhen: %s,\n", t, goConditionSlice(a.AppliesToGearWhen))
		}
		if a.KombiGroup != "" {
			fmt.Fprintf(buf, "%s\t\tKombiGroup: %q,\n", t, a.KombiGroup)
		}
		if len(a.Subfields) > 0 {
			fmt.Fprintf(buf, "%s\t\tSubfields: ", t)
			writeGoAttributes(buf, a.Subfields, depth+2)
			fmt.Fprintf(buf, ",\n")
		}
		fmt.Fprintf(buf, "%s\t},\n", t)
	}
	fmt.Fprintf(buf, "%s}", t)
}

// writeGoRecommended emits a *RecommendedConstraints literal into buf at the
// gear_type literal's indent depth (3 tabs).
func writeGoRecommended(buf *bytes.Buffer, rc *RecommendedConstraints) {
	buf.WriteString("\t\t\tRecommended: &RecommendedConstraints{\n")
	if len(rc.Attributes) > 0 {
		buf.WriteString("\t\t\t\tAttributes: []RecommendedAttribute{\n")
		for _, ra := range rc.Attributes {
			fmt.Fprintf(buf, "\t\t\t\t\t{Key: %q", ra.Key)
			if len(ra.Values) > 0 {
				fmt.Fprintf(buf, ", Values: %s", goAnySlice(ra.Values))
			}
			buf.WriteString("},\n")
		}
		buf.WriteString("\t\t\t\t},\n")
	}
	buf.WriteString("\t\t\t},\n")
}

// goConditionSlice renders a []Condition Go literal.
func goConditionSlice(conds []Condition) string {
	var buf bytes.Buffer
	buf.WriteString("[]Condition{")
	for i, c := range conds {
		if i > 0 {
			buf.WriteString(", ")
		}
		fmt.Fprintf(&buf, "{Ref: %q, Op: %q", c.Ref, c.Op)
		if c.Value != nil {
			fmt.Fprintf(&buf, ", Value: %s", goAnyLiteral(c.Value))
		}
		if len(c.Values) > 0 {
			fmt.Fprintf(&buf, ", Values: %s", goAnySlice(c.Values))
		}
		buf.WriteString("}")
	}
	buf.WriteString("}")
	return buf.String()
}

// goAnySlice renders an []any Go literal preserving each element's runtime
// type via goAnyLiteral.
func goAnySlice(values []any) string {
	var buf bytes.Buffer
	buf.WriteString("[]any{")
	for i, v := range values {
		if i > 0 {
			buf.WriteString(", ")
		}
		buf.WriteString(goAnyLiteral(v))
	}
	buf.WriteString("}")
	return buf.String()
}

// goAnyLiteral renders a single value as a Go literal. YAML decodes numeric
// scalars as int or float64 and quoted strings as string; we preserve those.
func goAnyLiteral(v any) string {
	switch val := v.(type) {
	case nil:
		return "nil"
	case string:
		return fmt.Sprintf("%q", val)
	case bool:
		return fmt.Sprintf("%t", val)
	case int:
		return fmt.Sprintf("%d", val)
	case int64:
		return fmt.Sprintf("%d", val)
	case float64:
		// Render whole numbers without a fractional part for readability.
		if val == float64(int64(val)) {
			return fmt.Sprintf("%d", int64(val))
		}
		return fmt.Sprintf("%g", val)
	default:
		return fmt.Sprintf("%q", fmt.Sprintf("%v", val))
	}
}

func goStringSlice(values []string) string {
	var buf bytes.Buffer
	buf.WriteString("[]string{")
	for i, v := range values {
		if i > 0 {
			buf.WriteString(", ")
		}
		fmt.Fprintf(&buf, "%q", v)
	}
	buf.WriteString("}")
	return buf.String()
}
