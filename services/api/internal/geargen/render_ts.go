func labelsFor(labelDE string, labels LocaleMap) LocaleMap {
	out := make(LocaleMap, len(labels)+1)
	for key, value := range labels {
		if value != "" {
			out[key] = value
		}
	}
	if out["de"] == "" {
		out["de"] = labelDE
	}
	return out
}
