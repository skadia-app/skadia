package geargen_test

import (
	"strings"
	"testing"

	"github.com/skadia-app/skadia/services/api/internal/geargen"
)

func TestRenderTSEmitsNewAttributeFields(t *testing.T) {
	schema := &geargen.Schema{
		AssignmentRoles: []geargen.AssignmentRole{
			{Key: "primary", LabelDE: "Hauptausrüstung", Labels: geargen.LocaleMap{"de": "Hauptausrüstung", "en": "Primary gear"}},
		},
		OptionSets: []geargen.OptionSet{},
		Attributes: []geargen.Attribute{
			{
				Key:          "bike.travel",
				LabelDE:      "Federweg",
				Labels:       geargen.LocaleMap{"de": "Federweg", "en": "Travel"},
				ValueType:    "unit_number",
				UnitGroup:    "length",
				AllowedUnits: []string{"mm"},
				Required:     true,
			},
		},
		GearTypes: []geargen.GearType{
			{
				Key:                      "bike",
				LabelDE:                  "Fahrrad",
				Labels:                   geargen.LocaleMap{"de": "Fahrrad", "en": "Bike"},
				Scope:                    "bike",
				DefaultAssignmentRoleKey: "primary",
			},
		},
	}
	out, err := geargen.RenderTS(schema)
	if err != nil {
		t.Fatalf("RenderTS() error = %v", err)
	}
	for _, want := range []string{
		"unitGroup?: string",
		"allowedUnits?: string[]",
		"required?: boolean",
		`"unitGroup": "length"`,
		`"allowedUnits"`,
		`"required": true`,
		`"labels":`,
		`"en": "Travel"`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("RenderTS() output missing %q\n--- output ---\n%s", want, out)
		}
	}
}

func TestRenderTSEmitsShowWhenAndSlotsAndComponentTypes(t *testing.T) {
	schema := &geargen.Schema{
		AssignmentRoles: []geargen.AssignmentRole{{Key: "primary", LabelDE: "Haupt"}},
		OptionSets:      []geargen.OptionSet{},
		Attributes: []geargen.Attribute{
			{Key: "test.a", LabelDE: "A", ValueType: "string"},
			{
				Key:       "test.b",
				LabelDE:   "B",
				ValueType: "string",
				ShowWhen:  &geargen.ShowWhenSpec{Field: "test.a", Value: "x"},
			},
		},
		GearTypes: []geargen.GearType{
			{
				Key:                      "bike",
				LabelDE:                  "Fahrrad",
				Scope:                    "bike",
				DefaultAssignmentRoleKey: "primary",
				Slots: []geargen.GearTypeSlot{
					{Key: "frame", LabelDE: "Rahmen", ComponentType: "bike.frame"},
				},
			},
		},
		ComponentTypes: []geargen.ComponentType{
			{Key: "bike.frame", LabelDE: "Rahmen", AttributeKeys: []string{"a"}},
		},
	}
	out, err := geargen.RenderTS(schema)
	if err != nil {
		t.Fatalf("RenderTS() error = %v", err)
	}
	for _, want := range []string{
		"export interface ShowWhenSpec",
		"showWhen?: ShowWhenSpec",
		"export interface GearTypeSlot",
		"slots?: GearTypeSlot[]",
		"export interface ComponentType",
		"componentTypes?: ComponentType[]",
		`"showWhen"`,
		`"slots"`,
		`"componentTypes"`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("RenderTS() output missing %q", want)
		}
	}
}

func TestRenderTSEmitsSchemaTypes(t *testing.T) {
	schema := minimalSchemaForRender()
	out, err := geargen.RenderTS(schema)
	if err != nil {
		t.Fatalf("RenderTS() error = %v", err)
	}
	src := out

	for _, want := range []string{
		"// Code generated by geargen; DO NOT EDIT.",
		"export interface AssignmentRole",
		"export interface OptionSet",
		"export interface OptionValue",
		"export interface Attribute",
		"export interface GearType",
		"export interface GearSchema",
		"export const gearSchema: GearSchema =",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("RenderTS() output missing %q\n--- output ---\n%s", want, src)
		}
	}

	// Verify schema data is present.
	for _, want := range []string{
		`"primary"`,
		`"bike.frame_material"`,
		`"bike.frame_size_cm"`,
		`"bike"`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("RenderTS() output missing value %q", want)
		}
	}
}
