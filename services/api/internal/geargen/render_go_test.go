func TestRenderGoOutputIsValidGo(t *testing.T) {
	schema := minimalSchemaForRender()
	out, err := geargen.RenderGo(schema)
	if err != nil {
		t.Fatalf("RenderGo() error = %v", err)
	}
	// format.Source would have been called inside RenderGo; if output is returned
	// without error, it is valid Go. Verify it is non-empty and starts with the
	// package declaration.
	src := strings.TrimSpace(string(out))
	if !strings.HasPrefix(src, "// Code generated by geargen; DO NOT EDIT.") {
		t.Errorf("RenderGo() output does not start with generated header:\n%s", src[:min(200, len(src))])
	}
}
