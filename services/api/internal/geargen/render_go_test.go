func minimalSchemaForRender() *geargen.Schema {
	return &geargen.Schema{
		AssignmentRoles: []geargen.AssignmentRole{
			{Key: "primary", LabelDE: "Hauptausrüstung", UniquePerActivity: true},
		},
		OptionSets: []geargen.OptionSet{
			{
				Key: "bike.frame_material",
				Options: []geargen.OptionValue{
					{Key: "aluminum", LabelDE: "Aluminium"},
				},
			},
		},
		Attributes: []geargen.Attribute{
			{Key: "bike.frame_size_cm", LabelDE: "Rahmengröße (cm)", ValueType: "number"},
		},
		GearTypes: []geargen.GearType{
			{
				Key:                      "bike",
				LabelDE:                  "Fahrrad",
				Scope:                    "bike",
				DefaultAssignmentRoleKey: "primary",
				AttributeKeys:            []string{"bike.frame_size_cm"},
			},
		},
	}
}

func TestRenderGoEmitsSchemaTypes(t *testing.T) {
	schema := minimalSchemaForRender()
	out, err := geargen.RenderGo(schema)
	if err != nil {
		t.Fatalf("RenderGo() error = %v", err)
	}
	src := string(out)

	for _, want := range []string{
		"package gear",
		"// Code generated by geargen; DO NOT EDIT.",
		"type AssignmentRole struct",
		"type OptionSet struct",
		"type OptionValue struct",
		"type Attribute struct",
		"type GearType struct",
		"var Schema =",
		"func LookupAttribute(",
		"func LookupGearType(",
		"func LookupOptionSet(",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("RenderGo() output missing %q\n--- output ---\n%s", want, src)
		}
	}

	// Verify the schema data is present.
	for _, want := range []string{
		`"primary"`,
		`"Hauptausrüstung"`,
		`"bike.frame_material"`,
		`"bike.frame_size_cm"`,
		`"bike"`,
		`"Fahrrad"`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("RenderGo() output missing value %q", want)
		}
	}
}

func TestRenderGoEmitsNewAttributeFields(t *testing.T) {
	schema := &geargen.Schema{
		AssignmentRoles: []geargen.AssignmentRole{
			{Key: "primary", LabelDE: "Hauptausrüstung"},
		},
		OptionSets: []geargen.OptionSet{},
		Attributes: []geargen.Attribute{
			{
				Key:          "bike.travel",
				LabelDE:      "Federweg",
				ValueType:    "unit_number",
				UnitGroup:    "length",
				AllowedUnits: []string{"mm", "in"},
				Required:     true,
			},
		},
		GearTypes: []geargen.GearType{
			{
				Key:                      "bike",
				LabelDE:                  "Fahrrad",
				Scope:                    "bike",
				DefaultAssignmentRoleKey: "primary",
			},
		},
	}
	out, err := geargen.RenderGo(schema)
	if err != nil {
		t.Fatalf("RenderGo() error = %v", err)
	}
	src := string(out)

	for _, want := range []string{
		"UnitGroup         string",
		"AllowedUnits      []string",
		"Required          bool",
		`"length"`,
		`[]string{"mm", "in"}`,
		`true`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("RenderGo() output missing %q\n--- output ---\n%s", want, src)
		}
	}
	// Verify the new fields are actually emitted in the data section.
	if !strings.Contains(src, "UnitGroup:") {
		t.Error("RenderGo() data section missing UnitGroup field")
	}
	if !strings.Contains(src, "AllowedUnits:") {
		t.Error("RenderGo() data section missing AllowedUnits field")
	}
	if !strings.Contains(src, "Required:") {
		t.Error("RenderGo() data section missing Required field")
	}
}

