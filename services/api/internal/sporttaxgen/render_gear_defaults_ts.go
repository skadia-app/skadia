package sporttaxgen

import (
	"bytes"
	"fmt"
)

func RenderTSGearDefaultProjection(projection GearDefaultProjection) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("export const GENERATED_GEAR_DEFAULT_MANUAL_OPTIONS = [\n")
	for _, option := range projection.ManualOptions {
		fmt.Fprintf(&buf, "  { value: %q, label: %q },\n", option.SportType, option.LabelDE)
	}
	buf.WriteString("] as const\n")
	return buf.Bytes(), nil
}
