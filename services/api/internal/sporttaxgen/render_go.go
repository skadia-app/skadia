package sporttaxgen

import (
	"bytes"
	"fmt"
	"go/format"
)

func RenderGo(t Taxonomy) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("package sport\n\n")

	buf.WriteString("var generatedCategories = []Category{\n")
	for _, c := range t.Categories {
		fmt.Fprintf(&buf, "\t{Key: %q, LabelDE: %q, Color: %q},\n", c.Key, c.Labels["de"], c.Color.LightHex)
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var generatedSportDefs = []SportDef{\n")
	for _, s := range t.Sports {
		fmt.Fprintf(&buf, "\t{\n")
		fmt.Fprintf(&buf, "\t\tSportType: %q, CategoryKey: %q, LabelDE: %q, AutoTitleDE: %q,\n", s.SportType, s.CategoryKey, s.Labels["de"], s.AutoTitles["de"])
		fmt.Fprintf(&buf, "\t\tSegmentGroup: %q, TypicallyHasGPS: %t, MovingThreshold: %v, IsIndoor: %t,\n", s.SegmentGroup, s.TypicallyHasGPS, s.MovingThreshold, s.IsIndoor)
		fmt.Fprintf(&buf, "\t\tLifecycle: %q, Selectable: %t,\n", s.Lifecycle, *s.Selectable)
		fmt.Fprintf(&buf, "\t\tTraits: %s,\n", renderGoTraits(s.Traits))
		if defaults := effectiveSportModifierDefaults(s); defaults != nil {
			fmt.Fprintf(&buf, "\t\tModifierDefaults: %s,\n", renderGoModifierDefaults(defaults))
		}
		if len(s.SubTypes) > 0 {
			buf.WriteString("\t\tSubTypes: map[string]SubTypeDef{\n")
			for _, st := range s.SubTypes {
				fmt.Fprintf(&buf, "\t\t\t%q: {SubType: %q, LabelDE: %q, DetailDE: %q, AutoTitleDE: %q, Selectable: %t", st.SubType, st.SubType, st.Labels["de"], st.Details["de"], st.AutoTitles["de"], *st.Selectable)
				if st.MovingThreshold != nil {
					fmt.Fprintf(&buf, ", MovingThreshold: ptrFloat64(%v)", *st.MovingThreshold)
				}
				fmt.Fprintf(&buf, ", Traits: %s", renderGoTraits(EffectiveSubTypeTraits(s, st)))
				if st.ModifierDefaults != nil {
					fmt.Fprintf(&buf, ", ModifierDefaults: %s", renderGoModifierDefaults(st.ModifierDefaults))
				}
				buf.WriteString("},\n")
			}
			buf.WriteString("\t\t},\n")
			fmt.Fprintf(&buf, "\t\tSubTypeOrder: %s,\n", goSubTypeOrder(s.SubTypes))
		}
		fmt.Fprintf(&buf, "\t},\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

func goSubTypeOrder(subTypes []SubType) string {
	values := make([]string, 0, len(subTypes))
	for _, subType := range subTypes {
		values = append(values, subType.SubType)
	}
	return goStringArray(values)
}

func renderGoTraits(traits Traits) string {
	return fmt.Sprintf("SportTraits{Environments: %s, MovementFamilies: %s, EquipmentFamilies: %s, ActivityForm: %q, PropulsionModes: %s}",
		goStringArray(traits.Environments),
		goStringArray(traits.MovementFamilies),
		goStringArray(traits.EquipmentFamilies),
		traits.ActivityForm,
		goStringArray(traits.PropulsionModes),
	)
}

func goStringArray(values []string) string {
	if len(values) == 0 {
		return "[]string{}"
	}
	var buf bytes.Buffer
	buf.WriteString("[]string{")
	for _, value := range values {
		fmt.Fprintf(&buf, "%q,", value)
	}
	buf.WriteString("}")
	return buf.String()
}

func effectiveSportModifierDefaults(s Sport) *ModifierDefaults {
	if s.ModifierDefaults == nil && !s.IsIndoor {
		return nil
	}
	defaults := ModifierDefaults{}
	if s.ModifierDefaults != nil {
		defaults = *s.ModifierDefaults
	}
	if s.IsIndoor && defaults.IsIndoor == nil {
		isIndoor := true
		defaults.IsIndoor = &isIndoor
	}
	return &defaults
}

func renderGoModifierDefaults(defaults *ModifierDefaults) string {
	if defaults == nil {
		return "ModifierDefaults{}"
	}
	var buf bytes.Buffer
	buf.WriteString("ModifierDefaults{")
	if defaults.IsIndoor != nil {
		fmt.Fprintf(&buf, "IsIndoor: ptrBool(%t),", *defaults.IsIndoor)
	}
	buf.WriteString("}")
	return buf.String()
}
