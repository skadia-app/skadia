package sporttaxgen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
)

func RenderGo(t Taxonomy) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("package sport\n\n")

	buf.WriteString("var generatedCategories = []Category{\n")
	for _, c := range t.Categories {
		fmt.Fprintf(&buf, "\t{Key: %q, LabelDE: %q, Color: %q},\n", c.Key, c.Labels["de"], c.Color.LightHex)
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var generatedSportDefs = []SportDef{\n")
	for _, s := range t.Sports {
		fmt.Fprintf(&buf, "\t{\n")
		fmt.Fprintf(&buf, "\t\tSportType: %q, CategoryKey: %q, LabelDE: %q, AutoTitleDE: %q,\n", s.SportType, s.CategoryKey, s.Labels["de"], s.AutoTitles["de"])
		fmt.Fprintf(&buf, "\t\tSegmentGroup: %q, TypicallyHasGPS: %t, MovingThreshold: %v, IsIndoor: %t,\n", s.SegmentGroup, s.TypicallyHasGPS, s.MovingThreshold, s.IsIndoor)
		fmt.Fprintf(&buf, "\t\tLifecycle: %q, Selectable: %t,\n", s.Lifecycle, *s.Selectable)
		fmt.Fprintf(&buf, "\t\tTraits: %s,\n", renderGoTraits(s.Traits))
		if defaults := effectiveSportModifierDefaults(s); defaults != nil {
			fmt.Fprintf(&buf, "\t\tModifierDefaults: %s,\n", renderGoModifierDefaults(defaults))
		}
		if len(s.SubTypes) > 0 {
			buf.WriteString("\t\tSubTypes: map[string]SubTypeDef{\n")
			for _, st := range s.SubTypes {
				fmt.Fprintf(&buf, "\t\t\t%q: {SubType: %q, LabelDE: %q, DetailDE: %q, AutoTitleDE: %q, Selectable: %t", st.SubType, st.SubType, st.Labels["de"], st.Details["de"], st.AutoTitles["de"], *st.Selectable)
				if st.MovingThreshold != nil {
					fmt.Fprintf(&buf, ", MovingThreshold: ptrFloat64(%v)", *st.MovingThreshold)
				}
				fmt.Fprintf(&buf, ", Traits: %s", renderGoTraits(EffectiveSubTypeTraits(s, st)))
				if st.ModifierDefaults != nil {
					fmt.Fprintf(&buf, ", ModifierDefaults: %s", renderGoModifierDefaults(st.ModifierDefaults))
				}
				buf.WriteString("},\n")
			}
			buf.WriteString("\t\t},\n")
			fmt.Fprintf(&buf, "\t\tSubTypeOrder: %s,\n", goSubTypeOrder(s.SubTypes))
		}
		fmt.Fprintf(&buf, "\t},\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

func goSubTypeOrder(subTypes []SubType) string {
	values := make([]string, 0, len(subTypes))
	for _, subType := range subTypes {
		values = append(values, subType.SubType)
	}
	return goStringArray(values)
}

func renderGoTraits(traits Traits) string {
	return fmt.Sprintf("SportTraits{Environments: %s, MovementFamilies: %s, EquipmentFamilies: %s, ActivityForm: %q, PropulsionModes: %s}",
		goStringArray(traits.Environments),
		goStringArray(traits.MovementFamilies),
		goStringArray(traits.EquipmentFamilies),
		traits.ActivityForm,
		goStringArray(traits.PropulsionModes),
	)
}

func goStringArray(values []string) string {
	if len(values) == 0 {
		return "[]string{}"
	}
	var buf bytes.Buffer
	buf.WriteString("[]string{")
	for _, value := range values {
		fmt.Fprintf(&buf, "%q,", value)
	}
	buf.WriteString("}")
	return buf.String()
}

func effectiveSportModifierDefaults(s Sport) *ModifierDefaults {
	if s.ModifierDefaults == nil && !s.IsIndoor {
		return nil
	}
	defaults := ModifierDefaults{}
	if s.ModifierDefaults != nil {
		for key, value := range *s.ModifierDefaults {
			defaults[key] = value
		}
	}
	if s.IsIndoor {
		if _, ok := defaults["is_indoor"]; !ok {
			defaults["is_indoor"] = true
		}
	}
	return &defaults
}

func renderGoModifierDefaults(defaults *ModifierDefaults) string {
	if defaults == nil {
		return "ModifierDefaults{}"
	}
	var buf bytes.Buffer
	buf.WriteString("ModifierDefaults{")
	keys := make([]string, 0, len(*defaults))
	for key := range *defaults {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		fmt.Fprintf(&buf, "%q: %t,", key, (*defaults)[key])
	}
	buf.WriteString("}")
	return buf.String()
}

func RenderGoModifiers(registry ModifierRegistry) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("package sport\n\n")

	buf.WriteString("type SportModifierDef struct {\n")
	buf.WriteString("\tKey string\n")
	buf.WriteString("\tLabelDE string\n")
	buf.WriteString("\tGoField string\n")
	buf.WriteString("\tTSField string\n")
	buf.WriteString("\tJSONKey string\n")
	buf.WriteString("\tActivityColumn string\n")
	buf.WriteString("\tApplicabilitySource string\n")
	buf.WriteString("\tActionName string\n")
	buf.WriteString("\tActionParam string\n")
	buf.WriteString("\tShadowFSToken string\n")
	buf.WriteString("\tCapabilities map[string]bool\n")
	buf.WriteString("}\n\n")

	buf.WriteString("var generatedSportModifiers = []SportModifierDef{\n")
	for _, modifier := range registry.Modifiers {
		fmt.Fprintf(&buf, "\t{\n")
		fmt.Fprintf(&buf, "\t\tKey: %q, LabelDE: %q, GoField: %q, TSField: %q, JSONKey: %q,\n", modifier.Key, modifier.Labels["de"], modifier.GoField, modifier.TSField, modifier.JSONKey)
		fmt.Fprintf(&buf, "\t\tActivityColumn: %q, ApplicabilitySource: %q, ActionName: %q, ActionParam: %q, ShadowFSToken: %q,\n", modifier.ActivityColumn, modifier.ApplicabilitySource, modifier.ActionName, modifier.ActionParam, modifier.ShadowFSToken)
		fmt.Fprintf(&buf, "\t\tCapabilities: %s,\n", renderGoModifierCapabilities(modifier.Capabilities))
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n\n")

	buf.WriteString("func SportModifierKeys() []string {\n")
	buf.WriteString("\tkeys := make([]string, 0, len(generatedSportModifiers))\n")
	buf.WriteString("\tfor _, modifier := range generatedSportModifiers {\n")
	buf.WriteString("\t\tkeys = append(keys, modifier.Key)\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn keys\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func SportModifierByKey(key string) (SportModifierDef, bool) {\n")
	buf.WriteString("\tfor _, modifier := range generatedSportModifiers {\n")
	buf.WriteString("\t\tif modifier.Key == key {\n")
	buf.WriteString("\t\t\treturn cloneSportModifierDef(modifier), true\n")
	buf.WriteString("\t\t}\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn SportModifierDef{}, false\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func SportModifierKeysWithCapability(capability string) []string {\n")
	buf.WriteString("\tkeys := make([]string, 0, len(generatedSportModifiers))\n")
	buf.WriteString("\tfor _, modifier := range generatedSportModifiers {\n")
	buf.WriteString("\t\tif modifier.Capabilities[capability] {\n")
	buf.WriteString("\t\t\tkeys = append(keys, modifier.Key)\n")
	buf.WriteString("\t\t}\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn keys\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func SportModifierHasCapability(key, capability string) bool {\n")
	buf.WriteString("\tfor _, modifier := range generatedSportModifiers {\n")
	buf.WriteString("\t\tif modifier.Key == key {\n")
	buf.WriteString("\t\t\treturn modifier.Capabilities[capability]\n")
	buf.WriteString("\t\t}\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn false\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func SportModifierLabelDE(key string) string {\n")
	buf.WriteString("\tmodifier, ok := SportModifierByKey(key)\n")
	buf.WriteString("\tif !ok {\n")
	buf.WriteString("\t\treturn \"\"\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn modifier.LabelDE\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func SportModifierExists(key string) bool {\n")
	buf.WriteString("\tfor _, modifier := range generatedSportModifiers {\n")
	buf.WriteString("\t\tif modifier.Key == key {\n")
	buf.WriteString("\t\t\treturn true\n")
	buf.WriteString("\t\t}\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn false\n")
	buf.WriteString("}\n\n")

	buf.WriteString("func cloneSportModifierDef(modifier SportModifierDef) SportModifierDef {\n")
	buf.WriteString("\tclone := modifier\n")
	buf.WriteString("\tclone.Capabilities = make(map[string]bool, len(modifier.Capabilities))\n")
	buf.WriteString("\tfor key, enabled := range modifier.Capabilities {\n")
	buf.WriteString("\t\tclone.Capabilities[key] = enabled\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn clone\n")
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go modifiers: %w", err)
	}
	return formatted, nil
}

func renderGoModifierCapabilities(capabilities ModifierCapabilities) string {
	var buf bytes.Buffer
	buf.WriteString("map[string]bool{")
	for _, capability := range modifierCapabilityNames() {
		fmt.Fprintf(&buf, "%q: %t,", capability, capabilities.Enabled(capability))
	}
	buf.WriteString("}")
	return buf.String()
}
