package sporttaxgen

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"strings"
)

func RenderTS(t Taxonomy, source []byte) ([]byte, error) {
	var buf bytes.Buffer
	sum := sha256.Sum256(source)

	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "export const GENERATED_SPORT_TAXONOMY_SOURCE_SHA256 = '%x'\n\n", sum)

	buf.WriteString("export const GENERATED_CATEGORIES = [\n")
	for _, c := range t.Categories {
		fmt.Fprintf(&buf, "  { key: %s, label: %s, color: %s },\n", tsString(c.Key), tsString(c.Labels["de"]), tsString(c.Color.LightHex))
	}
	buf.WriteString("] as const\n\n")

	buf.WriteString("export const GENERATED_SPORT_DEFS = [\n")
	for _, s := range t.Sports {
		buf.WriteString("  {\n")
		fmt.Fprintf(&buf, "    sportType: %s,\n", tsString(s.SportType))
		fmt.Fprintf(&buf, "    categoryKey: %s,\n", tsString(s.CategoryKey))
		fmt.Fprintf(&buf, "    segmentGroup: %s,\n", tsString(s.SegmentGroup))
		fmt.Fprintf(&buf, "    label: %s,\n", tsString(s.Labels["de"]))
		fmt.Fprintf(&buf, "    autoTitle: %s,\n", tsString(s.AutoTitles["de"]))
		fmt.Fprintf(&buf, "    typicallyHasGPS: %t,\n", s.TypicallyHasGPS)
		fmt.Fprintf(&buf, "    movingThreshold: %v,\n", s.MovingThreshold)
		fmt.Fprintf(&buf, "    isIndoor: %t,\n", s.IsIndoor)
		fmt.Fprintf(&buf, "    lifecycle: %s,\n", tsString(s.Lifecycle))
		fmt.Fprintf(&buf, "    selectable: %t,\n", *s.Selectable)
		fmt.Fprintf(&buf, "    traits: %s,\n", tsTraits(s.Traits))
		if defaults := effectiveSportModifierDefaults(s); defaults != nil {
			fmt.Fprintf(&buf, "    modifierDefaults: %s,\n", tsModifierDefaults(defaults))
		}
		if len(s.SubTypes) > 0 {
			buf.WriteString("    subTypes: [\n")
			for _, st := range s.SubTypes {
				fmt.Fprintf(&buf, "      { subType: %s, label: %s, detail: %s, selectable: %t", tsString(st.SubType), tsString(st.Labels["de"]), tsString(st.Details["de"]), *st.Selectable)
				if st.MovingThreshold != nil {
					fmt.Fprintf(&buf, ", movingThreshold: %v", *st.MovingThreshold)
				}
				fmt.Fprintf(&buf, ", traits: %s", tsTraits(EffectiveSubTypeTraits(s, st)))
				if st.ModifierDefaults != nil {
					fmt.Fprintf(&buf, ", modifierDefaults: %s", tsModifierDefaults(st.ModifierDefaults))
				}
				buf.WriteString(" },\n")
			}
			buf.WriteString("    ],\n")
		} else {
			buf.WriteString("    subTypes: [],\n")
		}
		buf.WriteString("  },\n")
	}
	buf.WriteString("] as const\n")

	return buf.Bytes(), nil
}

func tsString(s string) string {
	escaped := strings.ReplaceAll(s, `\`, `\\`)
	escaped = strings.ReplaceAll(escaped, `'`, `\'`)
	escaped = strings.ReplaceAll(escaped, "\n", `\n`)
	escaped = strings.ReplaceAll(escaped, "\r", `\r`)
	escaped = strings.ReplaceAll(escaped, "\t", `\t`)
	escaped = strings.ReplaceAll(escaped, "\u2028", `\u2028`)
	escaped = strings.ReplaceAll(escaped, "\u2029", `\u2029`)
	return "'" + escaped + "'"
}

func tsTraits(traits Traits) string {
	return fmt.Sprintf("{ environments: %s, movementFamilies: %s, equipmentFamilies: %s, activityForm: %s, propulsionModes: %s }",
		tsStringArray(traits.Environments),
		tsStringArray(traits.MovementFamilies),
		tsStringArray(traits.EquipmentFamilies),
		tsString(traits.ActivityForm),
		tsStringArray(traits.PropulsionModes),
	)
}

func tsModifierDefaults(defaults *ModifierDefaults) string {
	if defaults == nil {
		return "{}"
	}
	parts := []string{}
	if defaults.IsIndoor != nil {
		parts = append(parts, fmt.Sprintf("isIndoor: %t", *defaults.IsIndoor))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func tsStringArray(values []string) string {
	if len(values) == 0 {
		return "[]"
	}
	encoded := make([]string, 0, len(values))
	for _, value := range values {
		encoded = append(encoded, tsString(value))
	}
	return "[" + strings.Join(encoded, ", ") + "]"
}

func RenderTSModifiers(registry ModifierRegistry) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")

	buf.WriteString("export const GENERATED_SPORT_MODIFIER_KEYS = [")
	for i, modifier := range registry.Modifiers {
		if i > 0 {
			buf.WriteString(", ")
		}
		buf.WriteString(tsString(modifier.Key))
	}
	buf.WriteString("] as const\n\n")
	buf.WriteString("export type SportModifierKey = typeof GENERATED_SPORT_MODIFIER_KEYS[number]\n\n")

	buf.WriteString("export const GENERATED_SPORT_MODIFIERS = [\n")
	for _, modifier := range registry.Modifiers {
		buf.WriteString("  {\n")
		fmt.Fprintf(&buf, "    key: %s,\n", tsString(modifier.Key))
		fmt.Fprintf(&buf, "    label: %s,\n", tsString(modifier.Labels["de"]))
		fmt.Fprintf(&buf, "    goField: %s,\n", tsString(modifier.GoField))
		fmt.Fprintf(&buf, "    tsField: %s,\n", tsString(modifier.TSField))
		fmt.Fprintf(&buf, "    jsonKey: %s,\n", tsString(modifier.JSONKey))
		fmt.Fprintf(&buf, "    activityColumn: %s,\n", tsString(modifier.ActivityColumn))
		fmt.Fprintf(&buf, "    applicabilitySource: %s,\n", tsString(modifier.ApplicabilitySource))
		fmt.Fprintf(&buf, "    actionName: %s,\n", tsString(modifier.ActionName))
		fmt.Fprintf(&buf, "    actionParam: %s,\n", tsString(modifier.ActionParam))
		fmt.Fprintf(&buf, "    shadowFSToken: %s,\n", tsString(modifier.ShadowFSToken))
		fmt.Fprintf(&buf, "    capabilities: %s,\n", tsModifierCapabilities(modifier.Capabilities))
		if modifier.TagSync != nil {
			fmt.Fprintf(&buf, "    tagSync: { systemTag: %s", tsString(modifier.TagSync.SystemTag))
			if modifier.TagSync.OnlySportType != "" {
				fmt.Fprintf(&buf, ", onlySportType: %s", tsString(modifier.TagSync.OnlySportType))
			}
			if modifier.TagSync.LabelContext != "" {
				fmt.Fprintf(&buf, ", labelContext: %s", tsString(modifier.TagSync.LabelContext))
			}
			buf.WriteString(" },\n")
		}
		buf.WriteString("  },\n")
	}
	buf.WriteString("] as const\n")

	return buf.Bytes(), nil
}

func tsModifierCapabilities(capabilities ModifierCapabilities) string {
	parts := make([]string, 0, len(modifierCapabilityNames()))
	for _, capability := range modifierCapabilityNames() {
		parts = append(parts, fmt.Sprintf("%s: %t", capability, capabilities.Enabled(capability)))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}
