package sporttaxgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"strings"
	"text/template"

	"github.com/skadia-app/skadia/services/api/internal/applicablemodifiers"
)

var knownSubsystemsTemplate = template.Must(template.New("knownSubsystems").Parse(
	`// Code generated by applicablemodifiersgen; DO NOT EDIT.

package sporttaxgen

// knownSubsystems is the set of valid subsystem names for the subsystems[] field.
// Generated from config/applicable-modifiers/subsystems.yaml via scripts/generate-applicable-modifiers.sh.
var knownSubsystems = map[string]struct{}{
{{- range .}}
	{{printf "%q" .}}: {},
{{- end}}
}
`))

// RenderKnownSubsystems renders the Go source for the knownSubsystems map,
// populated from the given registry entries. Names are emitted in registry order.
func RenderKnownSubsystems(subs []applicablemodifiers.Subsystem) (string, error) {
	names := make([]string, 0, len(subs))
	for _, s := range subs {
		names = append(names, s.Name)
	}
	var buf bytes.Buffer
	if err := knownSubsystemsTemplate.Execute(&buf, names); err != nil {
		return "", fmt.Errorf("render knownSubsystems template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return "", fmt.Errorf("format generated Go (knownSubsystems): %w", err)
	}
	return string(formatted), nil
}

// RenderSubsystemsEnumFragment renders the JSONSchema fragment file that
// defines the subsystemName enum. The fragment is referenced from
// modifiers.schema.json via $ref.
func RenderSubsystemsEnumFragment(subs []applicablemodifiers.Subsystem) (string, error) {
	names := make([]string, 0, len(subs))
	for _, s := range subs {
		names = append(names, s.Name)
	}
	// Marshal with deterministic key ordering via a custom approach.
	// json.MarshalIndent does not guarantee key order for map[string]any.
	buf, err := marshalSubsystemsFragment(nil, names)
	if err != nil {
		return "", fmt.Errorf("marshal subsystems enum fragment: %w", err)
	}
	return string(buf) + "\n", nil
}

// marshalSubsystemsFragment produces stable, human-readable JSON for the fragment.
// We hand-write the JSON to ensure deterministic key order without reflection magic.
func marshalSubsystemsFragment(_ map[string]any, names []string) ([]byte, error) {
	// Build enum array JSON manually for stable order.
	enumItems := make([]string, len(names))
	for i, n := range names {
		b, err := json.Marshal(n)
		if err != nil {
			return nil, err
		}
		enumItems[i] = "      " + string(b)
	}

	var sb strings.Builder
	sb.WriteString("{\n")
	sb.WriteString(`  "$schema": "https://json-schema.org/draft/2020-12/schema",`)
	sb.WriteString("\n")
	sb.WriteString(`  "$id": "https://skadia.local/schema/sport-taxonomy/_subsystems_enum.schema.json",`)
	sb.WriteString("\n")
	sb.WriteString(`  "$defs": {`)
	sb.WriteString("\n")
	sb.WriteString(`    "subsystemName": {`)
	sb.WriteString("\n")
	sb.WriteString(`      "type": "string",`)
	sb.WriteString("\n")
	sb.WriteString(`      "enum": [`)
	sb.WriteString("\n")
	sb.WriteString(strings.Join(enumItems, ",\n"))
	sb.WriteString("\n")
	sb.WriteString("      ]\n")
	sb.WriteString("    }\n")
	sb.WriteString("  }\n")
	sb.WriteString("}")
	return []byte(sb.String()), nil
}
