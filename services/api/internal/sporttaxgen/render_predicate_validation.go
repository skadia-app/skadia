package sporttaxgen

import (
	"bytes"
	"sort"
	"strings"
)

type predicateSQLSubtypeRow struct {
	sport   string
	subType string
}

type predicateSQLSegmentTupleRow struct {
	segmentType string
	sport       string
	subType     string
}

func RenderPredicateValidationSQL(taxonomy Taxonomy, segmentProjection ExpandedSegmentProjection) ([]byte, error) {
	sports := append([]Sport(nil), taxonomy.Sports...)
	sort.Slice(sports, func(i, j int) bool { return sports[i].SportType < sports[j].SportType })

	subtypes := make([]predicateSQLSubtypeRow, 0)
	for _, sport := range sports {
		for _, subType := range sport.SubTypes {
			subtypes = append(subtypes, predicateSQLSubtypeRow{sport: sport.SportType, subType: subType.SubType})
		}
	}
	sort.Slice(subtypes, func(i, j int) bool {
		if subtypes[i].sport != subtypes[j].sport {
			return subtypes[i].sport < subtypes[j].sport
		}
		return subtypes[i].subType < subtypes[j].subType
	})
	segmentTuples := predicateSQLSegmentTuples(segmentProjection)

	var buf bytes.Buffer
	buf.WriteString("-- Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("-- Validates persisted sport.Predicate arrays only: sport/sub_type keys, no rule modifiers.\n")
	buf.WriteString("-- Empty arrays are valid here for explicit no-match segment predicates; table constraints add non-empty checks where needed.\n")
	buf.WriteString("CREATE OR REPLACE FUNCTION fn_validate_predicates(p JSONB)\n")
	buf.WriteString("RETURNS BOOLEAN\nLANGUAGE sql\nIMMUTABLE\nSET search_path = public\nAS $$\n")
	buf.WriteString("WITH allowed_sports(sport) AS (\n    VALUES\n")
	writeSQLValueRows(&buf, renderSportRows(sports), 8)
	buf.WriteString("\n),\nallowed_subtypes(sport, sub_type) AS (\n    VALUES\n")
	writeSQLValueRows(&buf, renderSubtypeRows(subtypes), 8)
	buf.WriteString(`
),
items AS (
    SELECT value AS pred
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(p) = 'array' THEN p ELSE '[]'::jsonb END)
)
SELECT
    COALESCE(jsonb_typeof(p) = 'array', false)
    AND NOT EXISTS (
        SELECT 1
        FROM items
        WHERE jsonb_typeof(pred) <> 'object'
           OR EXISTS (
                SELECT 1
                FROM jsonb_object_keys(pred) AS pred_keys(key)
                WHERE pred_keys.key NOT IN ('sport', 'sub_type')
           )
           OR NOT (pred ? 'sport')
           OR jsonb_typeof(pred->'sport') <> 'string'
           OR NOT EXISTS (SELECT 1 FROM allowed_sports s WHERE s.sport = pred->>'sport')
           OR (
                pred ? 'sub_type'
                AND (
                    jsonb_typeof(pred->'sub_type') <> 'string'
                    OR NOT (
                        pred->>'sub_type' = ''
                        OR EXISTS (
                            SELECT 1
                            FROM allowed_subtypes st
                            WHERE st.sport = pred->>'sport'
                              AND st.sub_type = pred->>'sub_type'
                        )
                    )
                )
           )
    );
$$;
`)
	buf.WriteString("CREATE OR REPLACE FUNCTION fn_validate_segment_predicates_for_type(seg_type TEXT, p JSONB)\n")
	buf.WriteString("RETURNS BOOLEAN\nLANGUAGE sql\nIMMUTABLE\nSET search_path = public\nAS $$\n")
	buf.WriteString("WITH allowed_segment_tuples(segment_type, sport, sub_type) AS (\n    VALUES\n")
	writeSQLValueRows(&buf, renderSegmentTupleRows(segmentTuples), 8)
	buf.WriteString(`
),
items AS (
    SELECT value AS pred
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(p) = 'array' THEN p ELSE '[]'::jsonb END)
)
SELECT
    fn_validate_predicates(p)
    AND (
        seg_type = 'lift'
        OR NOT EXISTS (
            SELECT 1
            FROM items
            WHERE NOT EXISTS (
                SELECT 1
                FROM allowed_segment_tuples ast
                WHERE ast.segment_type = seg_type
                  AND ast.sport = pred->>'sport'
                  AND (
                      ast.sub_type = COALESCE(pred->>'sub_type', '')
                      OR ast.sub_type = ''
                  )
            )
        )
    );
$$;
`)
	return buf.Bytes(), nil
}

func predicateSQLSegmentTuples(projection ExpandedSegmentProjection) []predicateSQLSegmentTupleRow {
	activeDomainsBySegmentType := map[string]map[string]struct{}{}
	for _, segmentType := range projection.SegmentTypes {
		active := map[string]struct{}{}
		for _, domain := range segmentType.ActiveDomains {
			active[domain] = struct{}{}
		}
		activeDomainsBySegmentType[segmentType.Key] = active
	}
	rows := make([]predicateSQLSegmentTupleRow, 0, len(projection.Entries))
	for _, entry := range projection.Entries {
		if _, ok := activeDomainsBySegmentType[entry.SegmentType][entry.Domain]; !ok {
			continue
		}
		rows = append(rows, predicateSQLSegmentTupleRow{
			segmentType: entry.SegmentType,
			sport:       entry.SportType,
			subType:     entry.SubType,
		})
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].segmentType != rows[j].segmentType {
			return rows[i].segmentType < rows[j].segmentType
		}
		if rows[i].sport != rows[j].sport {
			return rows[i].sport < rows[j].sport
		}
		return rows[i].subType < rows[j].subType
	})
	return rows
}

func renderSportRows(sports []Sport) []string {
	rows := make([]string, 0, len(sports))
	for _, sport := range sports {
		rows = append(rows, "("+sqlStringLiteral(sport.SportType)+")")
	}
	return rows
}

func renderSubtypeRows(subtypes []predicateSQLSubtypeRow) []string {
	rows := make([]string, 0, len(subtypes))
	for _, subType := range subtypes {
		rows = append(rows, "("+sqlStringLiteral(subType.sport)+","+sqlStringLiteral(subType.subType)+")")
	}
	return rows
}

func renderSegmentTupleRows(tuples []predicateSQLSegmentTupleRow) []string {
	rows := make([]string, 0, len(tuples))
	for _, tuple := range tuples {
		rows = append(rows, "("+sqlStringLiteral(tuple.segmentType)+","+sqlStringLiteral(tuple.sport)+","+sqlStringLiteral(tuple.subType)+")")
	}
	if len(rows) == 0 {
		return []string{"(NULL,NULL,NULL)"}
	}
	return rows
}

func writeSQLValueRows(buf *bytes.Buffer, rows []string, indent int) {
	prefix := strings.Repeat(" ", indent)
	for i, row := range rows {
		if i == 0 {
			buf.WriteString(prefix)
		} else {
			buf.WriteString(", ")
		}
		buf.WriteString(row)
	}
}

func sqlStringLiteral(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}
