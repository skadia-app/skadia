package sporttaxgen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
)

func RenderGoSourceAliases(sources []SourceAliases) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("package sport\n\n")
	buf.WriteString("var generatedSourceAliases = map[Source][]sourceAliasDef{\n")

	sortedSources := append([]SourceAliases(nil), sources...)
	sort.Slice(sortedSources, func(i, j int) bool {
		return sortedSources[i].Source < sortedSources[j].Source
	})
	for _, source := range sortedSources {
		sourceConst, err := renderGoSourceConst(source.Source)
		if err != nil {
			return nil, err
		}
		aliases := append([]SourceAlias(nil), source.Aliases...)
		sort.SliceStable(aliases, func(i, j int) bool {
			if aliases[i].Raw == aliases[j].Raw {
				return aliases[i].RawSub < aliases[j].RawSub
			}
			return aliases[i].Raw < aliases[j].Raw
		})
		fmt.Fprintf(&buf, "\t%s: {\n", sourceConst)
		for _, alias := range aliases {
			fmt.Fprintf(&buf, "\t\t{RawSport: %q", alias.Raw)
			if alias.RawSub != "" {
				fmt.Fprintf(&buf, ", RawSub: %q", alias.RawSub)
			}
			fmt.Fprintf(&buf, ", Tuple: Tuple{SportType: %q", alias.SportType)
			if alias.SubType != "" {
				fmt.Fprintf(&buf, ", SubType: %q", alias.SubType)
			}
			buf.WriteString("}")
			if alias.Modifiers != nil {
				fmt.Fprintf(&buf, ", Patch: %s", renderGoAliasModifierPatch(alias.Modifiers))
			}
			buf.WriteString("},\n")
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go source aliases: %w", err)
	}
	return formatted, nil
}

func renderGoSourceConst(source string) (string, error) {
	switch source {
	case "legacy":
		return "SourceLegacy", nil
	case "fit":
		return "SourceFITFile", nil
	case "gpx":
		return "SourceGPXFile", nil
	case "tcx":
		return "SourceTCXFile", nil
	case "garmin":
		return "SourceGarminCourse", nil
	case "strava":
		return "SourceStrava", nil
	case "komoot":
		return "SourceKomoot", nil
	default:
		return "", fmt.Errorf("unknown source alias namespace %q", source)
	}
}

func renderGoAliasModifierPatch(modifiers *SourceAliasModifiers) string {
	var buf bytes.Buffer
	buf.WriteString("ModifierPatch{")
	if modifiers.IsElectric != nil {
		fmt.Fprintf(&buf, "IsElectric: ptrBool(%t),", *modifiers.IsElectric)
	}
	if modifiers.IsIndoor != nil {
		fmt.Fprintf(&buf, "IsIndoor: ptrBool(%t),", *modifiers.IsIndoor)
	}
	if modifiers.IsVirtual != nil {
		fmt.Fprintf(&buf, "IsVirtual: ptrBool(%t),", *modifiers.IsVirtual)
	}
	buf.WriteString("}")
	return buf.String()
}
