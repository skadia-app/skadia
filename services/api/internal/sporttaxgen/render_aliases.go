package sporttaxgen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

func RenderGoSourceAliases(sources []SourceAliases) ([]byte, error) {
	return RenderGoSourceAliasesWithGearDefaults(sources, GearDefaultProjection{})
}

func RenderTSSourceAliases(sources []SourceAliases) ([]byte, error) {
	var legacyAliases []SourceAlias
	for _, source := range sources {
		if source.Source != "legacy" {
			continue
		}
		legacyAliases = append(legacyAliases, source.Aliases...)
	}
	sort.SliceStable(legacyAliases, func(i, j int) bool {
		if legacyAliases[i].Raw == legacyAliases[j].Raw {
			return legacyAliases[i].RawSub < legacyAliases[j].RawSub
		}
		return legacyAliases[i].Raw < legacyAliases[j].Raw
	})

	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("export const GENERATED_LEGACY_ALIASES = [\n")
	for _, alias := range legacyAliases {
		if alias.RawSub != "" {
			continue
		}
		renderTSAlias(&buf, alias)
	}
	buf.WriteString("] as const\n\n")
	buf.WriteString("export const GENERATED_LEGACY_SUBTYPE_ALIASES = [\n")
	for _, alias := range legacyAliases {
		if alias.RawSub == "" {
			continue
		}
		renderTSAlias(&buf, alias)
	}
	buf.WriteString("] as const\n")
	return buf.Bytes(), nil
}

func RenderGoSourceAliasesWithGearDefaults(sources []SourceAliases, gearDefaults GearDefaultProjection) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("package sport\n\n")
	buf.WriteString("var generatedSourceAliases = map[Source][]sourceAliasDef{\n")

	sortedSources := append([]SourceAliases(nil), sources...)
	sort.Slice(sortedSources, func(i, j int) bool {
		return sortedSources[i].Source < sortedSources[j].Source
	})
	for _, source := range sortedSources {
		sourceConst, err := renderGoSourceConst(source.Source)
		if err != nil {
			return nil, err
		}
		aliases := append([]SourceAlias(nil), source.Aliases...)
		sort.SliceStable(aliases, func(i, j int) bool {
			if aliases[i].Raw == aliases[j].Raw {
				return aliases[i].RawSub < aliases[j].RawSub
			}
			return aliases[i].Raw < aliases[j].Raw
		})
		fmt.Fprintf(&buf, "\t%s: {\n", sourceConst)
		for _, alias := range aliases {
			fmt.Fprintf(&buf, "\t\t{RawSport: %q", alias.Raw)
			if alias.RawSub != "" {
				fmt.Fprintf(&buf, ", RawSub: %q", alias.RawSub)
			}
			fmt.Fprintf(&buf, ", Tuple: Tuple{SportType: %q", alias.SportType)
			if alias.SubType != "" {
				fmt.Fprintf(&buf, ", SubType: %q", alias.SubType)
			}
			buf.WriteString("}")
			if alias.Modifiers != nil {
				fmt.Fprintf(&buf, ", Patch: %s", renderGoAliasModifierPatch(alias.Modifiers))
			}
			buf.WriteString("},\n")
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")
	if err := renderGoGearDefaultProjection(&buf, gearDefaults); err != nil {
		return nil, err
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go source aliases: %w", err)
	}
	return formatted, nil
}

func renderTSAlias(buf *bytes.Buffer, alias SourceAlias) {
	fmt.Fprintf(buf, "  { raw: %s", tsString(alias.Raw))
	if alias.RawSub != "" {
		fmt.Fprintf(buf, ", rawSub: %s", tsString(alias.RawSub))
	}
	fmt.Fprintf(buf, ", sportType: %s", tsString(alias.SportType))
	if alias.SubType != "" {
		fmt.Fprintf(buf, ", subType: %s", tsString(alias.SubType))
	}
	if alias.Modifiers != nil {
		fmt.Fprintf(buf, ", modifiers: %s", tsAliasModifiers(alias.Modifiers))
	}
	buf.WriteString(" },\n")
}

func tsAliasModifiers(modifiers *SourceAliasModifiers) string {
	if modifiers == nil {
		return "{}"
	}
	parts := []string{}
	if modifiers.IsElectric != nil {
		parts = append(parts, fmt.Sprintf("isElectric: %t", *modifiers.IsElectric))
	}
	if modifiers.IsIndoor != nil {
		parts = append(parts, fmt.Sprintf("isIndoor: %t", *modifiers.IsIndoor))
	}
	if modifiers.IsVirtual != nil {
		parts = append(parts, fmt.Sprintf("isVirtual: %t", *modifiers.IsVirtual))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func renderGoSourceConst(source string) (string, error) {
	switch source {
	case "legacy":
		return "SourceLegacy", nil
	case "fit":
		return "SourceFITFile", nil
	case "gpx":
		return "SourceGPXFile", nil
	case "tcx":
		return "SourceTCXFile", nil
	case "garmin":
		return "SourceGarminCourse", nil
	case "strava":
		return "SourceStrava", nil
	case "strava_route":
		return "SourceStravaRoute", nil
	case "komoot":
		return "SourceKomoot", nil
	default:
		return "", fmt.Errorf("unknown source alias namespace %q", source)
	}
}

func renderGoGearDefaultProjection(buf *bytes.Buffer, projection GearDefaultProjection) error {
	buf.WriteString("\nvar generatedGearDefaultSportsBySource = map[Source]map[string]string{\n")
	for _, source := range projection.Sources {
		sourceConst, err := renderGoSourceConst(source.Source)
		if err != nil {
			return err
		}
		fmt.Fprintf(buf, "\t%s: {\n", sourceConst)
		for _, alias := range source.Aliases {
			fmt.Fprintf(buf, "\t\t%q: %q,\n", alias.Raw, alias.SportType)
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	buf.WriteString("\nvar generatedGearDefaultStorageSportOptions = []GearDefaultSportOption{\n")
	for _, option := range projection.StorageOptions {
		fmt.Fprintf(buf, "\t{SportType: %q, LabelDE: %q},\n", option.SportType, option.LabelDE)
	}
	buf.WriteString("}\n")

	buf.WriteString("\nvar generatedGearDefaultManualSportOptions = []GearDefaultSportOption{\n")
	for _, option := range projection.ManualOptions {
		fmt.Fprintf(buf, "\t{SportType: %q, LabelDE: %q},\n", option.SportType, option.LabelDE)
	}
	buf.WriteString("}\n")
	return nil
}

func renderGoAliasModifierPatch(modifiers *SourceAliasModifiers) string {
	var buf bytes.Buffer
	buf.WriteString("ModifierPatch{")
	if modifiers.IsElectric != nil {
		fmt.Fprintf(&buf, "IsElectric: ptrBool(%t),", *modifiers.IsElectric)
	}
	if modifiers.IsIndoor != nil {
		fmt.Fprintf(&buf, "IsIndoor: ptrBool(%t),", *modifiers.IsIndoor)
	}
	if modifiers.IsVirtual != nil {
		fmt.Fprintf(&buf, "IsVirtual: ptrBool(%t),", *modifiers.IsVirtual)
	}
	buf.WriteString("}")
	return buf.String()
}
