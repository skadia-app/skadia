func RenderGoProjections(activityPresets []ExpandedActivityFilterPreset, segmentProjection ExpandedSegmentProjection, ruleProjection ExpandedRuleProjection) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("package sport\n\n")
	buf.WriteString("var generatedActivityFilterProjectionPresets = []ActivityFilterProjectionPreset{\n")
	for _, preset := range activityPresets {
		fmt.Fprintf(&buf, "\t{Key: %q, LabelDE: %q, Groups: []ActivityFilterProjectionGroup{\n", preset.Key, preset.Label["de"])
		for _, group := range preset.Groups {
			fmt.Fprintf(&buf, "\t\t{Key: %q, LabelDE: %q, Leaves: []ActivityFilterProjectionLeaf{\n", group.Key, group.Label["de"])
			for _, leaf := range group.Leaves {
				fmt.Fprintf(&buf, "\t\t\t{SportType: %q, SubType: %q, LabelDE: %q},\n", leaf.SportType, leaf.SubType, leaf.Label["de"])
			}
			buf.WriteString("\t\t}},\n")
		}
		buf.WriteString("\t}},\n")
	}
	buf.WriteString("}\n")
	buf.WriteString("\nvar generatedSegmentProjectionDomains = []SegmentProjectionDomain{\n")
	for _, domain := range segmentProjection.Domains {
		fmt.Fprintf(&buf, "\t{Key: %q, LabelDE: %q, Status: %q},\n", domain.Key, domain.Label["de"], domain.Status)
	}
	buf.WriteString("}\n")
	buf.WriteString("\nvar generatedSegmentProjectionSegmentTypes = []SegmentProjectionSegmentType{\n")
	for _, segmentType := range segmentProjection.SegmentTypes {
		fmt.Fprintf(&buf, "\t{Key: %q, LabelDE: %q, ActiveDomains: %#v, CompatibilityRole: %q},\n", segmentType.Key, segmentType.Label["de"], segmentType.ActiveDomains, segmentType.CompatibilityRole)
	}
	buf.WriteString("}\n")
	buf.WriteString("\nvar generatedSegmentProjectionEntries = []SegmentProjectionEntry{\n")
	for _, entry := range segmentProjection.Entries {
		fmt.Fprintf(&buf, "\t{SegmentType: %q, Domain: %q, SportType: %q, SubType: %q, SportGroup: %q},\n", entry.SegmentType, entry.Domain, entry.SportType, entry.SubType, entry.SportGroup)
	}
	buf.WriteString("}\n")
	buf.WriteString("\nvar generatedActivityTraitBuckets = buildGeneratedActivityTraitBuckets([]activityTraitBucketTuple{\n")
	seenActivityTraitTuples := map[string]struct{}{}
	for _, bucket := range segmentProjection.ActivityTraitBuckets {
		tupleKey := projectionTupleKey(bucket.SportType, bucket.SubType)
		if _, ok := seenActivityTraitTuples[tupleKey]; ok {
			continue
		}
		seenActivityTraitTuples[tupleKey] = struct{}{}
		fmt.Fprintf(&buf, "\t{SportType: %q, SubType: %q, MovementFamilies: %#v, PropulsionModes: %#v, EquipmentFamilies: %#v, ActivityForm: %q, EnvironmentState: %q},\n",
			bucket.SportType,
			bucket.SubType,
			bucket.MovementFamilies,
			bucket.PropulsionModes,
			bucket.EquipmentFamilies,
			bucket.ActivityForm,
			bucket.EnvironmentState,
		)
	}
	buf.WriteString("})\n")
	buf.WriteString("\nvar generatedRuleTupleOptions = []RuleTupleOption{\n")
	for _, option := range ruleProjection.TupleOptions {
		fmt.Fprintf(&buf, "\t{SportType: %q, SubType: %q, LabelDE: %q},\n", option.SportType, option.SubType, option.Label["de"])
	}
	buf.WriteString("}\n")
	buf.WriteString("\nvar generatedRuleModifierProjections = map[string][]RuleModifierProjection{\n")
	for _, option := range ruleProjection.TupleOptions {
		fmt.Fprintf(&buf, "\t%q: {\n", projectionTupleKey(option.SportType, option.SubType))
		for _, modifier := range option.Modifiers {
			fmt.Fprintf(&buf, "\t\t{Key: %q, LabelDE: %q, ConditionApplicable: %t, ActionApplicable: %t, RenderExisting: %t},\n", modifier.Key, modifier.Label["de"], modifier.ConditionApplicable, modifier.ActionApplicable, modifier.RenderExisting)
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")
	buf.WriteString("\nvar generatedRuleTraitProjections = []RuleTraitProjection{\n")
	for _, condition := range ruleProjection.TraitConditions {
		fmt.Fprintf(&buf, "\t{Key: %q, Field: %q, LabelDE: %q, Options: []RuleTraitOption{\n", condition.Key, condition.Field, condition.Label["de"])
		for _, option := range condition.Options {
			fmt.Fprintf(&buf, "\t\t{Key: %q, LabelDE: %q},\n", option.Key, option.Label["de"])
		}
		buf.WriteString("\t}},\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go projections: %w", err)
	}
	return formatted, nil
}

func RenderTSActivityFilterProjections(presets []ExpandedActivityFilterPreset) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("export const GENERATED_ACTIVITY_FILTER_PRESETS = [\n")
	for _, preset := range presets {
		buf.WriteString("  {\n")
		fmt.Fprintf(&buf, "    key: %s,\n", tsString(preset.Key))
		fmt.Fprintf(&buf, "    label: %s,\n", tsString(preset.Label["de"]))
		buf.WriteString("    groups: [\n")
		for _, group := range preset.Groups {
			buf.WriteString("      {\n")
			fmt.Fprintf(&buf, "        key: %s,\n", tsString(group.Key))
			fmt.Fprintf(&buf, "        label: %s,\n", tsString(group.Label["de"]))
			buf.WriteString("        leaves: [\n")
			for _, leaf := range group.Leaves {
				if leaf.SubType == "" {
					fmt.Fprintf(&buf, "          { sportType: %s, label: %s },\n", tsString(leaf.SportType), tsString(leaf.Label["de"]))
					continue
				}
				fmt.Fprintf(&buf, "          { sportType: %s, subType: %s, label: %s },\n", tsString(leaf.SportType), tsString(leaf.SubType), tsString(leaf.Label["de"]))
			}
			buf.WriteString("        ],\n")
			buf.WriteString("      },\n")
		}
		buf.WriteString("    ],\n")
		buf.WriteString("  },\n")
	}
	buf.WriteString("] as const\n")
	return buf.Bytes(), nil
}

func RenderTSRuleProjection(projection ExpandedRuleProjection) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("export const GENERATED_RULE_TUPLE_OPTIONS = [\n")
	for _, option := range projection.TupleOptions {
		if option.SubType == "" {
			fmt.Fprintf(&buf, "  { sportType: %s, label: %s },\n", tsString(option.SportType), tsString(option.Label["de"]))
			continue
		}
		fmt.Fprintf(&buf, "  { sportType: %s, subType: %s, label: %s },\n", tsString(option.SportType), tsString(option.SubType), tsString(option.Label["de"]))
	}
	buf.WriteString("] as const\n\n")
	buf.WriteString("export const GENERATED_RULE_MODIFIER_PROJECTIONS = {\n")
	for _, option := range projection.TupleOptions {
		fmt.Fprintf(&buf, "  %s: [\n", tsString(projectionTupleKey(option.SportType, option.SubType)))
		for _, modifier := range option.Modifiers {
			fmt.Fprintf(&buf, "    { key: %s, label: %s, conditionApplicable: %t, actionApplicable: %t, renderExisting: %t },\n", tsString(modifier.Key), tsString(modifier.Label["de"]), modifier.ConditionApplicable, modifier.ActionApplicable, modifier.RenderExisting)
		}
		buf.WriteString("  ],\n")
	}
	buf.WriteString("} as const\n\n")
	buf.WriteString("export const GENERATED_RULE_TRAIT_PROJECTIONS = [\n")
	for _, condition := range projection.TraitConditions {
		buf.WriteString("  {\n")
		fmt.Fprintf(&buf, "    key: %s,\n", tsString(condition.Key))
		fmt.Fprintf(&buf, "    field: %s,\n", tsString(condition.Field))
		fmt.Fprintf(&buf, "    label: %s,\n", tsString(condition.Label["de"]))
		buf.WriteString("    operators: [")
		for i, op := range condition.Operators {
			if i > 0 {
				buf.WriteString(", ")
			}
			buf.WriteString(tsString(op))
		}
		buf.WriteString("],\n")
		buf.WriteString("    options: [\n")
		for _, option := range condition.Options {
			fmt.Fprintf(&buf, "      { value: %s, label: %s },\n", tsString(option.Key), tsString(option.Label["de"]))
		}
		buf.WriteString("    ],\n")
		buf.WriteString("  },\n")
	}
	buf.WriteString("] as const\n")
	return buf.Bytes(), nil
}

func RenderTSSegmentProjection(projection ExpandedSegmentProjection) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("export const GENERATED_SEGMENT_PROJECTION = {\n")
	buf.WriteString("  domains: [\n")
	for _, domain := range projection.Domains {
		fmt.Fprintf(&buf, "    { key: %s, label: %s, status: %s },\n", tsString(domain.Key), tsString(domain.Label["de"]), tsString(domain.Status))
	}
	buf.WriteString("  ],\n")
	buf.WriteString("  segmentTypes: [\n")
	for _, segmentType := range projection.SegmentTypes {
		fmt.Fprintf(&buf, "    { key: %s, label: %s, activeDomains: %s, compatibilityRole: %s },\n", tsString(segmentType.Key), tsString(segmentType.Label["de"]), tsStringArray(segmentType.ActiveDomains), tsString(segmentType.CompatibilityRole))
	}
	buf.WriteString("  ],\n")
	buf.WriteString("  routeOptions: [\n")
	for _, option := range projection.RouteOptions {
		if option.SubType == "" {
			fmt.Fprintf(&buf, "    { sportType: %s },\n", tsString(option.SportType))
			continue
		}
		fmt.Fprintf(&buf, "    { sportType: %s, subType: %s },\n", tsString(option.SportType), tsString(option.SubType))
	}
	buf.WriteString("  ],\n")
	buf.WriteString("  eligible: [\n")
	activeDomainsBySegmentType := map[string]map[string]struct{}{}
	for _, segmentType := range projection.SegmentTypes {
		activeDomainsBySegmentType[segmentType.Key] = map[string]struct{}{}
		for _, domain := range segmentType.ActiveDomains {
			activeDomainsBySegmentType[segmentType.Key][domain] = struct{}{}
		}
	}
	for _, entry := range projection.Entries {
		if _, ok := activeDomainsBySegmentType[entry.SegmentType][entry.Domain]; !ok {
			continue
		}
		if entry.SubType == "" {
			fmt.Fprintf(&buf, "    { segmentType: %s, domain: %s, sportType: %s, sportGroup: %s },\n", tsString(entry.SegmentType), tsString(entry.Domain), tsString(entry.SportType), tsString(entry.SportGroup))
			continue
		}
		fmt.Fprintf(&buf, "    { segmentType: %s, domain: %s, sportType: %s, subType: %s, sportGroup: %s },\n", tsString(entry.SegmentType), tsString(entry.Domain), tsString(entry.SportType), tsString(entry.SubType), tsString(entry.SportGroup))
	}
	buf.WriteString("  ],\n")
	buf.WriteString("} as const\n")
	return buf.Bytes(), nil
}
