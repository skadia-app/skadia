package sporttaxgen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

func RenderGoRecordsProjection(expanded ExpandedRecordsProjection, modifiers ModifierRegistry) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("package bestefforts\n\n")
	buf.WriteString("var generatedRecordGroups = []RecordGroup{\n")
	for _, group := range expanded.Groups {
		fmt.Fprintf(&buf, "\t{Key: %q, LabelDE: %q, MainCategory: %q, Color: %q, Badge: %q, Categories: []Category{\n", group.Key, group.Label["de"], group.MainCategory, group.Color, group.Badge)
		for _, category := range group.Categories {
			categoryType, err := goRecordCategoryType(category.Type)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&buf, "\t\t{Key: %q, Type: %s, DistanceM: %v, ElevationM: %v, DurationS: %d, Label: %q},\n", category.Key, categoryType, category.DistanceM, category.ElevationM, category.DurationS, category.Labels["de"])
		}
		buf.WriteString("\t}},\n")
	}
	buf.WriteString("}\n\n")
	buf.WriteString("var generatedRecordMainCategories = []RecordMainCategory{\n")
	for _, category := range expanded.MainCategories {
		fmt.Fprintf(&buf, "\t{Key: %q, LabelDE: %q, Color: %q, RecordGroups: %s, SubFilters: []RecordSubFilter{\n", category.Key, category.Label["de"], category.Color, goStringArray(category.RecordGroups))
		for _, filter := range category.SubFilters {
			fmt.Fprintf(&buf, "\t\t{Label: %q, RecordGroups: %s},\n", filter.Label, goStringArray(filter.RecordGroups))
		}
		buf.WriteString("\t}")
		if category.PowerCurve != nil {
			fmt.Fprintf(&buf, ", PowerCurve: &RecordPowerCurve{Label: %q, RecordGroups: %s}", category.PowerCurve.Label, goStringArray(category.PowerCurve.RecordGroups))
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n\n")
	buf.WriteString("var generatedRecordMatchRules = []RecordMatchRule{\n")
	for _, rule := range expanded.MatchRules {
		fmt.Fprintf(&buf, "\t{RecordGroup: %q, Priority: %d, Sequence: %d, SportType: %q, SubTypes: %s, ExcludeSubTypes: %s", rule.RecordGroup, rule.Priority, rule.Sequence, rule.SportType, goStringArray(rule.SubTypes), goStringArray(rule.ExcludeSubTypes))
		if len(rule.Modifiers) > 0 {
			fmt.Fprintf(&buf, ", Modifiers: %s", goRecordModifiers(rule.Modifiers, modifiers))
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n")
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go records projection: %w", err)
	}
	return formatted, nil
}

func RenderTSRecordsProjection(expanded ExpandedRecordsProjection, modifiers ModifierRegistry) ([]byte, error) {
	var buf bytes.Buffer
	categories, categoryOrder, categoryLabels, powerOrder := collectRecordCategoryMetadata(expanded)

	buf.WriteString("// Code generated by sporttaxgen; DO NOT EDIT.\n\n")
	buf.WriteString("export const GENERATED_RECORD_GROUPS = [\n")
	for _, group := range expanded.Groups {
		buf.WriteString("  {\n")
		fmt.Fprintf(&buf, "    key: %s,\n", tsString(group.Key))
		fmt.Fprintf(&buf, "    label: %s,\n", tsString(group.Label["de"]))
		fmt.Fprintf(&buf, "    mainCategory: %s,\n", tsString(group.MainCategory))
		fmt.Fprintf(&buf, "    color: %s,\n", tsString(group.Color))
		if group.Badge != "" {
			fmt.Fprintf(&buf, "    badge: %s,\n", tsString(group.Badge))
		}
		buf.WriteString("    categories: [\n")
		for _, category := range group.Categories {
			fmt.Fprintf(&buf, "      %s,\n", tsRecordCategory(category))
		}
		buf.WriteString("    ],\n")
		buf.WriteString("  },\n")
	}
	buf.WriteString("] as const\n\n")

	buf.WriteString("export const GENERATED_RECORD_MAIN_CATEGORIES = [\n")
	for _, category := range expanded.MainCategories {
		buf.WriteString("  {\n")
		fmt.Fprintf(&buf, "    key: %s,\n", tsString(category.Key))
		fmt.Fprintf(&buf, "    label: %s,\n", tsString(category.Label["de"]))
		fmt.Fprintf(&buf, "    color: %s,\n", tsString(category.Color))
		fmt.Fprintf(&buf, "    recordGroups: %s,\n", tsStringArray(category.RecordGroups))
		buf.WriteString("    subFilters: [\n")
		for _, filter := range category.SubFilters {
			fmt.Fprintf(&buf, "      { label: %s, recordGroups: %s },\n", tsString(filter.Label), tsStringArray(filter.RecordGroups))
		}
		buf.WriteString("    ],\n")
		if category.PowerCurve != nil {
			fmt.Fprintf(&buf, "    powerCurve: { label: %s, recordGroups: %s },\n", tsString(category.PowerCurve.Label), tsStringArray(category.PowerCurve.RecordGroups))
		}
		buf.WriteString("  },\n")
	}
	buf.WriteString("] as const\n\n")

	buf.WriteString("export const GENERATED_RECORD_MATCH_RULES = [\n")
	for _, rule := range expanded.MatchRules {
		buf.WriteString("  {")
		fmt.Fprintf(&buf, " recordGroup: %s, priority: %d, sequence: %d, sportType: %s", tsString(rule.RecordGroup), rule.Priority, rule.Sequence, tsString(rule.SportType))
		fmt.Fprintf(&buf, ", subTypes: %s", tsStringArray(rule.SubTypes))
		fmt.Fprintf(&buf, ", excludeSubTypes: %s", tsStringArray(rule.ExcludeSubTypes))
		fmt.Fprintf(&buf, ", modifiers: %s", tsRecordModifiers(rule.Modifiers, modifiers))
		buf.WriteString(" },\n")
	}
	buf.WriteString("] as const\n\n")

	buf.WriteString("export const GENERATED_RECORD_CATEGORIES = [\n")
	for _, category := range categories {
		fmt.Fprintf(&buf, "  %s,\n", tsRecordCategory(category))
	}
	buf.WriteString("] as const\n\n")
	fmt.Fprintf(&buf, "export const GENERATED_RECORD_CATEGORY_ORDER = %s as const\n", tsStringArray(categoryOrder))
	buf.WriteString("export const GENERATED_RECORD_CATEGORY_LABELS = {\n")
	for _, key := range categoryOrder {
		fmt.Fprintf(&buf, "  %s: %s,\n", tsString(key), tsString(categoryLabels[key]))
	}
	buf.WriteString("} as const\n")
	fmt.Fprintf(&buf, "export const GENERATED_RECORD_POWER_CATEGORY_ORDER = %s as const\n", tsStringArray(powerOrder))
	return buf.Bytes(), nil
}

func goRecordCategoryType(value string) (string, error) {
	switch value {
	case "time_lower":
		return "TypeTimeLower", nil
	case "value_higher":
		return "TypeValueHigher", nil
	case "value_superlative":
		return "TypeValueSuperlative", nil
	default:
		return "", fmt.Errorf("unknown record category type %q", value)
	}
}

func tsRecordCategory(category RecordCategory) string {
	parts := []string{
		fmt.Sprintf("key: %s", tsString(category.Key)),
		fmt.Sprintf("type: %s", tsString(category.Type)),
		fmt.Sprintf("label: %s", tsString(category.Labels["de"])),
	}
	if category.DistanceM > 0 {
		parts = append(parts, fmt.Sprintf("distanceM: %v", category.DistanceM))
	}
	if category.ElevationM > 0 {
		parts = append(parts, fmt.Sprintf("elevationM: %v", category.ElevationM))
	}
	if category.DurationS > 0 {
		parts = append(parts, fmt.Sprintf("durationS: %d", category.DurationS))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func goRecordModifiers(values RecordModifiers, modifiers ModifierRegistry) string {
	if len(values) == 0 {
		return "nil"
	}
	parts := []string{}
	for _, key := range modifiers.ModifierKeysWithCapability("record_grouping") {
		value := values[key]
		if value == nil {
			continue
		}
		parts = append(parts, fmt.Sprintf("%q: recordBoolPtr(%t)", key, *value))
	}
	if len(parts) == 0 {
		return "nil"
	}
	return "map[string]*bool{" + strings.Join(parts, ", ") + "}"
}

func tsRecordModifiers(values RecordModifiers, modifiers ModifierRegistry) string {
	parts := []string{}
	for _, key := range modifiers.ModifierKeysWithCapability("record_grouping") {
		value := values[key]
		if value == nil {
			continue
		}
		modifier, _ := modifiers.ModifierByKey(key)
		parts = append(parts, fmt.Sprintf("%s: %t", modifier.TSField, *value))
	}
	if len(parts) == 0 {
		return "{}"
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func collectRecordCategoryMetadata(expanded ExpandedRecordsProjection) ([]RecordCategory, []string, map[string]string, []string) {
	seen := map[string]struct{}{}
	labels := map[string]string{}
	categories := []RecordCategory{}
	order := []string{}
	powerOrder := []string{}
	for _, group := range expanded.Groups {
		for _, category := range group.Categories {
			if _, ok := seen[category.Key]; ok {
				continue
			}
			seen[category.Key] = struct{}{}
			categories = append(categories, cloneRecordCategory(category))
			order = append(order, category.Key)
			labels[category.Key] = category.Labels["de"]
			if category.DurationS > 0 {
				powerOrder = append(powerOrder, category.Key)
			}
		}
	}
	return categories, order, labels, powerOrder
}
