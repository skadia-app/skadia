package applicablemodifiers

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"text/template"
)

var goTemplate = template.Must(template.New("go").Parse(`// Code generated by applicablemodifiersgen; DO NOT EDIT.

package {{.PackageName}}

// {{.ExportPrefix}}ApplicableModifierKeys lists the modifier keys applicable to this subsystem.
var {{.ExportPrefix}}ApplicableModifierKeys = []string{
{{- range .Keys}}
	{{printf "%q" .}},
{{- end}}
}

// IsApplicableModifier reports whether key is applicable to this subsystem.
func IsApplicableModifier(key string) bool {
	for _, k := range {{.ExportPrefix}}ApplicableModifierKeys {
		if k == key {
			return true
		}
	}
	return false
}
`))

type goTemplateData struct {
	PackageName  string
	ExportPrefix string
	Keys         []string
}

// RenderGo renders a Go source file declaring the applicable modifier keys for a subsystem.
// packageName is the Go package name; exportPrefix is the PascalCase prefix for exported symbols.
func RenderGo(packageName, exportPrefix string, keys []string) (string, error) {
	var buf bytes.Buffer
	if err := goTemplate.Execute(&buf, goTemplateData{
		PackageName:  packageName,
		ExportPrefix: exportPrefix,
		Keys:         keys,
	}); err != nil {
		return "", fmt.Errorf("render Go template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return "", fmt.Errorf("format generated Go: %w", err)
	}
	return string(formatted), nil
}

var tsTemplate = template.Must(template.New("ts").Parse(`// Code generated by applicablemodifiersgen; DO NOT EDIT.

export const {{.ExportPrefix}}ApplicableModifierKeys: readonly string[] = [
{{- range .Keys}}
	'{{.}}',
{{- end}}
];

export function is{{.ExportPrefix}}ApplicableModifier(key: string): boolean {
	return ({{.ExportPrefix}}ApplicableModifierKeys as readonly string[]).includes(key);
}
`))

type tsTemplateData struct {
	ExportPrefix string
	Keys         []string
}

// RenderTS renders a TypeScript source file declaring the applicable modifier keys for a subsystem.
// subsystemName is used to derive the PascalCase export prefix.
func RenderTS(subsystemName string, keys []string) (string, error) {
	exportPrefix := toPascalCase(subsystemName)
	var buf bytes.Buffer
	if err := tsTemplate.Execute(&buf, tsTemplateData{
		ExportPrefix: exportPrefix,
		Keys:         keys,
	}); err != nil {
		return "", fmt.Errorf("render TS template: %w", err)
	}
	return buf.String(), nil
}

// toPascalCase converts a snake_case or lowercase name to PascalCase.
func toPascalCase(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' })
	var b strings.Builder
	for _, p := range parts {
		if len(p) > 0 {
			b.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return b.String()
}
