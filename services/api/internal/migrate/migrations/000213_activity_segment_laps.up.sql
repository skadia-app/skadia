CREATE TABLE activity_segment_laps (
    id                          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    activity_id                 UUID NOT NULL REFERENCES activities(id) ON DELETE CASCADE,
    message_index               SMALLINT NOT NULL,
    timestamp                   TIMESTAMPTZ,
    start_time                  TIMESTAMPTZ,
    name                        TEXT,
    uuid                        TEXT,
    status                      SMALLINT,
    manufacturer                SMALLINT,
    sport                       SMALLINT,
    sub_sport                   SMALLINT,
    event                       SMALLINT,
    event_type                  SMALLINT,
    event_group                 SMALLINT,
    sport_event                 SMALLINT,
    -- GPS
    start_lat                   DOUBLE PRECISION,
    start_lng                   DOUBLE PRECISION,
    end_lat                     DOUBLE PRECISION,
    end_lng                     DOUBLE PRECISION,
    nec_lat                     DOUBLE PRECISION,
    nec_lng                     DOUBLE PRECISION,
    swc_lat                     DOUBLE PRECISION,
    swc_lng                     DOUBLE PRECISION,
    -- Time
    total_elapsed_time_s        REAL,
    total_timer_time_s          REAL,
    total_moving_time_s         REAL,
    active_time_s               REAL,
    -- Distance / Elevation
    total_distance_m            REAL,
    total_ascent_m              INTEGER,
    total_descent_m             INTEGER,
    total_cycles                INTEGER,
    total_work_j                INTEGER,
    avg_altitude_m              REAL,
    max_altitude_m              REAL,
    min_altitude_m              REAL,
    total_fractional_ascent_m   REAL,
    total_fractional_descent_m  REAL,
    -- Speed
    avg_speed_ms                REAL,
    max_speed_ms                REAL,
    -- Heart Rate
    avg_heart_rate              SMALLINT,
    max_heart_rate              SMALLINT,
    min_heart_rate              SMALLINT,
    -- Cadence
    avg_cadence                 SMALLINT,
    max_cadence                 SMALLINT,
    avg_fractional_cadence      REAL,
    max_fractional_cadence      REAL,
    total_fractional_cycles     REAL,
    -- Power
    avg_power_w                 SMALLINT,
    max_power_w                 SMALLINT,
    normalized_power_w          SMALLINT,
    left_right_balance          REAL,
    -- Grade
    avg_grade_pct               REAL,
    avg_pos_grade_pct           REAL,
    avg_neg_grade_pct           REAL,
    max_pos_grade_pct           REAL,
    max_neg_grade_pct           REAL,
    -- Vertical Speed
    avg_pos_vertical_speed_ms   REAL,
    avg_neg_vertical_speed_ms   REAL,
    max_pos_vertical_speed_ms   REAL,
    max_neg_vertical_speed_ms   REAL,
    -- Temperature
    avg_temperature_c           SMALLINT,
    max_temperature_c           SMALLINT,
    gps_accuracy_m              SMALLINT,
    -- Calories
    total_calories              INTEGER,
    total_fat_calories          INTEGER,
    -- Pedal Analytics
    avg_left_torque_effectiveness_pct   REAL,
    avg_right_torque_effectiveness_pct  REAL,
    avg_left_pedal_smoothness_pct       REAL,
    avg_right_pedal_smoothness_pct      REAL,
    avg_combined_pedal_smoothness_pct   REAL,
    avg_left_pco_mm                     SMALLINT,
    avg_right_pco_mm                    SMALLINT,
    avg_left_power_phase_start_deg      REAL,
    avg_left_power_phase_end_deg        REAL,
    avg_left_power_phase_peak_start_deg REAL,
    avg_left_power_phase_peak_end_deg   REAL,
    avg_right_power_phase_start_deg     REAL,
    avg_right_power_phase_end_deg       REAL,
    avg_right_power_phase_peak_start_deg REAL,
    avg_right_power_phase_peak_end_deg  REAL,
    avg_power_position_w        INTEGER[],
    max_power_position_w        INTEGER[],
    avg_cadence_position        SMALLINT[],
    max_cadence_position        SMALLINT[],
    -- Standing / Sitting
    time_standing_s             REAL,
    stand_count                 INTEGER,
    -- Gear Shifts
    front_gear_shift_count      INTEGER,
    rear_gear_shift_count       INTEGER,
    -- Grit / Flow
    total_grit                  REAL,
    total_flow                  REAL,
    avg_grit                    REAL,
    avg_flow                    REAL,
    -- Misc
    repetition_num              INTEGER,
    wkt_step_index              SMALLINT,
    UNIQUE (activity_id, message_index)
);
CREATE INDEX idx_activity_segment_laps_activity ON activity_segment_laps(activity_id);
