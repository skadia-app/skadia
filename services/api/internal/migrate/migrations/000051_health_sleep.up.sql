CREATE TABLE health_sleep (
    id UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    calendar_date DATE NOT NULL,
    sleep_start_utc TIMESTAMPTZ NOT NULL,
    sleep_end_utc TIMESTAMPTZ NOT NULL,
    deep_seconds INTEGER,
    light_seconds INTEGER,
    rem_seconds INTEGER,
    awake_seconds INTEGER,
    score_overall INTEGER,
    score_quality INTEGER,
    score_duration INTEGER,
    score_deep INTEGER,
    score_rem INTEGER,
    respiration_avg DOUBLE PRECISION,
    awake_count INTEGER,
    restless_moments INTEGER,
    avg_sleep_stress DOUBLE PRECISION,
    source_type TEXT NOT NULL DEFAULT 'manual',
    extra_data JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, calendar_date)
);
