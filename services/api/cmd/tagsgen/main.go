// generateGo is the testable core: load + validate + render Go source.
func generateGo(yamlPath, schemaPath string) (string, error) {
	b, err := generateGoBytes(yamlPath, schemaPath)
	if err != nil {
		return "", err
	}
	return string(b), nil
}

func generateGoBytes(yamlPath, schemaPath string) ([]byte, error) {
	entries, err := loadAndValidate(yamlPath, schemaPath)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := goTemplate.Execute(&buf, entries); err != nil {
		return nil, fmt.Errorf("render Go template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt: %w\nraw output:\n%s", err, buf.String())
	}
	return formatted, nil
}

func generateTSBytes(yamlPath, schemaPath string) ([]byte, error) {
	entries, err := loadAndValidate(yamlPath, schemaPath)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tsTemplate.Execute(&buf, entries); err != nil {
		return nil, fmt.Errorf("render TS template: %w", err)
	}
	return buf.Bytes(), nil
}

// checkFile compares the on-disk content of path against want.
// Returns an error with a unified diff if they differ.
func checkFile(path string, want []byte) error {
	got, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read generated file %s: %w", path, err)
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("%s is stale; run generate-tags.sh to regenerate\n%s", path, unifiedDiff(path, got, want))
	}
	return nil
}

func unifiedDiff(path string, got, want []byte) string {
	gotLines := splitLines(got)
	wantLines := splitLines(want)

	prefix := 0
	for prefix < len(gotLines) && prefix < len(wantLines) && gotLines[prefix] == wantLines[prefix] {
		prefix++
	}
	suffix := 0
	for suffix < len(gotLines)-prefix &&
		suffix < len(wantLines)-prefix &&
		gotLines[len(gotLines)-1-suffix] == wantLines[len(wantLines)-1-suffix] {
		suffix++
	}

	gotChangeEnd := len(gotLines) - suffix
	wantChangeEnd := len(wantLines) - suffix
	contextStart := max(0, prefix-3)
	contextEnd := min(len(wantLines), wantChangeEnd+3)

	var diff strings.Builder
	fmt.Fprintf(&diff, "--- %s\n+++ expected\n@@\n", path)
	for _, line := range gotLines[contextStart:prefix] {
		fmt.Fprintf(&diff, " %s\n", line)
	}
	for _, line := range gotLines[prefix:gotChangeEnd] {
		fmt.Fprintf(&diff, "-%s\n", line)
	}
	for _, line := range wantLines[prefix:wantChangeEnd] {
		fmt.Fprintf(&diff, "+%s\n", line)
	}
	for _, line := range wantLines[wantChangeEnd:contextEnd] {
		fmt.Fprintf(&diff, " %s\n", line)
	}
	return strings.TrimRight(diff.String(), "\n")
}

func splitLines(data []byte) []string {
	text := strings.TrimSuffix(string(data), "\n")
	if text == "" {
		return nil
	}
	return strings.Split(text, "\n")
}

// toJSONCompatible recursively converts yaml.v3 map types to map[string]any
// so json.Marshal produces valid JSON for schema validation.
func toJSONCompatible(value any) (any, error) {
	switch typed := value.(type) {
	case map[any]any:
		out := make(map[string]any, len(typed))
		for k, v := range typed {
			ks, ok := k.(string)
			if !ok {
				return nil, fmt.Errorf("non-string YAML key %#v", k)
			}
			converted, err := toJSONCompatible(v)
			if err != nil {
				return nil, err
			}
			out[ks] = converted
		}
		return out, nil
	case map[string]any:
		out := make(map[string]any, len(typed))
		for k, v := range typed {
			converted, err := toJSONCompatible(v)
			if err != nil {
				return nil, err
			}
			out[k] = converted
		}
		return out, nil
	case []any:
		out := make([]any, 0, len(typed))
		for _, v := range typed {
			converted, err := toJSONCompatible(v)
			if err != nil {
				return nil, err
			}
			out = append(out, converted)
		}
		return out, nil
	default:
		return value, nil
	}
}
