// SystemTagSyncByModifierKey returns the SystemTagSync for the given modifier key.
// The second return value is false if the key has no system tag sync rule.
func SystemTagSyncByModifierKey(key string) (SystemTagSync, bool) {
	for _, s := range SystemTagSyncs {
		if s.ModifierKey == key {
			return s, true
		}
	}
	return SystemTagSync{}, false
}
`))

// tsTemplate renders the TypeScript output.
var tsTemplate = template.Must(template.New("ts").Parse(`// Code generated by cmd/tagsgen. DO NOT EDIT.

