CREATE TABLE activities (
    id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    file_hash               TEXT,
    title                   TEXT,
    title_auto              TEXT,
    title_is_manual         BOOLEAN DEFAULT false,
    description             TEXT,
    sport_type              TEXT NOT NULL,
    sub_type                TEXT,
    fit_sport_id            SMALLINT,
    fit_sub_sport_id        SMALLINT,
    is_ebike                BOOLEAN GENERATED ALWAYS AS (sport_type = 'e_biking') STORED,
    started_at              TIMESTAMPTZ NOT NULL,
    ended_at                TIMESTAMPTZ,
    elapsed_time_s          INTEGER,
    moving_time_s           INTEGER,
    distance_m              DOUBLE PRECISION,
    elevation_gain_m        DOUBLE PRECISION,
    elevation_loss_m        DOUBLE PRECISION,
    max_elevation_m         DOUBLE PRECISION,
    min_elevation_m         DOUBLE PRECISION,
    avg_speed_ms            DOUBLE PRECISION,
    max_speed_ms            DOUBLE PRECISION,
    avg_heart_rate          DOUBLE PRECISION,
    max_heart_rate          INTEGER,
    avg_power_w             DOUBLE PRECISION,
    max_power_w             INTEGER,
    normalized_power_w      DOUBLE PRECISION,
    avg_cadence             DOUBLE PRECISION,
    avg_temperature_c       DOUBLE PRECISION,
    tss                     DOUBLE PRECISION,
    trimp                   DOUBLE PRECISION,
    is_indoor               BOOLEAN DEFAULT false,
    start_location          GEOMETRY(Point, 4326),
    end_location            GEOMETRY(Point, 4326),
    original_file_bucket    TEXT,
    original_file_key       TEXT,
    original_file_format    TEXT,
    original_filename       TEXT,
    sidecar_meta_key        TEXT,
    gear_id                 UUID,
    tags                    TEXT[],
    enrichment_status       TEXT DEFAULT 'pending',
    visibility              TEXT NOT NULL DEFAULT 'private',
    created_at              TIMESTAMPTZ DEFAULT NOW(),
    updated_at              TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX ON activities (user_id, started_at DESC);
CREATE INDEX ON activities USING GIN (tags);
CREATE INDEX ON activities (file_hash) WHERE file_hash IS NOT NULL;
